from pydantic import BaseModel, Field
from typing import Dict

class PredictionResponse(BaseModel):
    symbol: str = Field(..., description="Stock ticker symbol")
    probabilities: Dict[str, float] = Field(..., description="Breakdown of probabilities generated by individual base models")
    ensemble_probability: float = Field(..., description="The unified weighted ensemble probability")
    timestamp: str = Field(..., description="ISO 8601 execution timestamp")
